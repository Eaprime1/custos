// Offline test table for .github/scripts/observation-log.js. No network, no GitHub.
// Run: bash tools/test_observation_log.sh

// Run the clock checks in the Shepherd's zone, not the machine's. A runner in UTC would
// otherwise hide a local-time bug: local and UTC read the same there.
process.env.TZ = 'America/Los_Angeles';

const {
  parseObservation, makeExcerpt, utcStamp, buildRow, inlineNote, parseRows, mergeLog, readEvent,
  MARKER, LOG_START, LOG_END, EXCERPT_MAX,
} = require('../.github/scripts/observation-log.js');

const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const FOOTER_WITH = '\n\n\ud83e\udd16 Generated with [Claude Code](https://claude.com/claude-code)';
const OWNER = { association: 'OWNER', authorType: 'User' };

const say = (text) => process.stdout.write(`${text}\n`);

let failed = 0;
let count = 0;
function check(name, ok, detail) {
  count += 1;
  if (!ok) {
    failed += 1;
    say(`FAIL  ${name}${detail ? `  ${detail}` : ''}`);
  }
}
const eq = (name, got, want) =>
  check(name, JSON.stringify(got) === JSON.stringify(want),
    `got ${JSON.stringify(got)}, want ${JSON.stringify(want)}`);

// ── What counts as an observation ───────────────────────────────────────────
// Each row: name, body, options, and what the parse must show.
// want is { stamp, text } for an observation, or { reject: true } for anything else.
const parseRows_ = [
  ['marker with stamp', 'shepherd observation 202610171254', OWNER, { stamp: '202610171254', text: '' }],
  ['marker without stamp', 'shepherd observation', OWNER, { stamp: null, text: '' }],
  ['case-insensitive', 'Shepherd Observation 202610171524', OWNER, { stamp: '202610171524', text: '' }],
  ['colon then text', 'shepherd observation 202610171524: check the podium', OWNER,
    { stamp: '202610171524', text: 'check the podium' }],
  ['dash then text', 'shepherd observation - check the podium', OWNER, { stamp: null, text: 'check the podium' }],
  ['text on following lines', 'shepherd observation 202610171524\nfirst\nsecond', OWNER,
    { stamp: '202610171524', text: 'first\nsecond' }],
  ['marker on a later line', 'Looks good.\n\nshepherd observation 202610171524\nrename it', OWNER,
    { stamp: '202610171524', text: 'rename it' }],
  ['three spaces in is fine', '   shepherd observation 202610171524', OWNER, { stamp: '202610171524', text: '' }],
  ['crlf line endings', 'shepherd observation 202610171524\r\nnote\r\n', OWNER, { stamp: '202610171524', text: 'note' }],
  ['eleven digits is not a stamp', 'shepherd observation 20261017152', OWNER, { stamp: null, text: '20261017152' }],
  ['thirteen digits is not a stamp', 'shepherd observation 2026101715241', OWNER, { stamp: null, text: '2026101715241' }],
  ['four spaces is indented code', '    shepherd observation 202610171524', OWNER, { reject: true }],
  ['tab is indented code', '\tshepherd observation 202610171524', OWNER, { reject: true }],
  ['mid-sentence is not a marker', 'I wrote a shepherd observation 202610171524 earlier', OWNER, { reject: true }],
  ['plural is not the marker', 'shepherd observations 202610171524', OWNER, { reject: true }],
  ['inline code is quoted', 'see `shepherd observation 202610171524`', OWNER, { reject: true }],
  ['fenced code is quoted', '```\nshepherd observation 202610171524\n```', OWNER, { reject: true }],
  ['tilde fence is quoted', '~~~\nshepherd observation 202610171524\n~~~', OWNER, { reject: true }],
  ['unterminated fence runs to the end', '```\nshepherd observation 202610171524', OWNER, { reject: true }],
  ['block quote is quoted', '> shepherd observation 202610171524', OWNER, { reject: true }],
  ['no marker at all', 'looks good to me', OWNER, { reject: true }],
  ['empty body', '', OWNER, { reject: true }],
  ['missing body', undefined, OWNER, { reject: true }],
  ['navigo footer (by)', `shepherd observation 202610171524${FOOTER}`, OWNER, { reject: true }],
  ['navigo footer (with)', `shepherd observation 202610171524${FOOTER_WITH}`, OWNER, { reject: true }],
  ['a bot', 'shepherd observation 202610171524', { association: 'OWNER', authorType: 'Bot' }, { reject: true }],
  ['a collaborator is not the owner', 'shepherd observation 202610171524',
    { association: 'COLLABORATOR', authorType: 'User' }, { reject: true }],
  ['a contributor', 'shepherd observation 202610171524', { association: 'CONTRIBUTOR', authorType: 'User' },
    { reject: true }],
  ['no association', 'shepherd observation 202610171524', {}, { reject: true }],
];

for (const [name, body, opts, want] of parseRows_) {
  const parsed = parseObservation(body, opts);
  if (want.reject) {
    check(`parse: ${name}`, parsed.ok === false && typeof parsed.reason === 'string', JSON.stringify(parsed));
  } else {
    check(`parse: ${name}`, parsed.ok === true && parsed.stamp === want.stamp && parsed.text === want.text, JSON.stringify(parsed));
  }
}

// ── The excerpt: safe to put in a table cell ────────────────────────────────
eq('excerpt: pipes escaped', makeExcerpt('a | b'), 'a \\| b');
eq('excerpt: newlines and runs of space collapse', makeExcerpt('a\n\n  b\tc'), 'a b c');
check('excerpt: a mention is defanged', !/@[A-Za-z]/.test(makeExcerpt('ping @someone now')),
  makeExcerpt('ping @someone now'));
check('excerpt: a forged row id cannot open a comment', !makeExcerpt('<!--obs:review-1--> hi').includes('<!--'));
check('excerpt: a forged marker cannot appear', !makeExcerpt(`${MARKER} x`).includes('<!--'));
check('excerpt: a closing marker cannot appear', !makeExcerpt(`${LOG_END} x`).includes('<!--'));
eq('excerpt: short text is untouched', makeExcerpt('rename it'), 'rename it');
{
  const long = makeExcerpt('x'.repeat(EXCERPT_MAX + 50));
  check('excerpt: long text is cut with an ellipsis', long.endsWith('\u2026') && Array.from(long).length === EXCERPT_MAX + 1,
    `length ${Array.from(long).length}`);
}
// The 240th character is a pipe: the cut happens before escaping, so the escape stays whole.
check('excerpt: a cut never splits an escape',
  makeExcerpt(`${'x'.repeat(EXCERPT_MAX - 1)}|y`).endsWith('x\\|…'),
  makeExcerpt(`${'x'.repeat(EXCERPT_MAX - 1)}|y`).slice(-6));

// ── The clock ───────────────────────────────────────────────────────────────
eq('utcStamp: a known time', utcStamp('2026-10-17T22:26:00Z'), '202610172226');
eq('utcStamp: midnight rolls over in UTC', utcStamp('2026-10-18T00:05:59Z'), '202610180005');
eq('utcStamp: accepts a Date', utcStamp(new Date('2026-01-02T03:04:00Z')), '202601020304');

// ── A row ───────────────────────────────────────────────────────────────────
const base = {
  id: 'review-5561541', kind: 'review', url: 'https://github.com/Eaprime1/custos/pull/462#pullrequestreview-5561541',
  by: 'Eaprime1', posted: '2026-10-17T21:54:00Z', stamp: '202610171254', head: 'abc1234def5678', excerpt: 'rename it',
};
{
  const built = buildRow(base);
  check('row: carries the typed stamp as written', built.line.includes('| 202610171254 |'), built.line);
  check('row: carries the posted time in UTC', built.line.startsWith('| 202610172154 |'), built.line);
  check('row: head is shortened', built.line.includes('`abc1234`') && !built.line.includes('def5678'), built.line);
  check('row: links the source', built.line.includes('[review](https://github.com/Eaprime1/custos/pull/462#pullrequestreview-5561541)'), built.line);
  check('row: ends with its hidden id', built.line.endsWith('<!--obs:review-5561541--> |'), built.line);
  eq('row: id is returned', built.id, 'review-5561541');
}
check('row: no stamp shows a dash', buildRow({ ...base, stamp: null }).line.includes('| \u2014 |'));
check('row: no text says so', buildRow({ ...base, excerpt: '' }).line.includes('(no text)'));
check('row: edited is shown', buildRow({ ...base, edited: true }).line.includes('\u00b7 edited'));
check('row: kind label for inline', buildRow({ ...base, id: 'rcomment-9', kind: 'inline' }).line.includes('[inline comment]'));
check('row: a non-GitHub url is not linked', !buildRow({ ...base, url: 'https://example.com/x' }).line.includes('](https://example.com'));
check('row: an odd login is not echoed', buildRow({ ...base, by: 'a|b' }).line.includes('@? |'));
check('row: an odd sha is not echoed', buildRow({ ...base, head: 'zz;rm' }).line.includes('`?`'));
for (const bad of ['', 'review', 'review-', 'Review-1', 'review-1x', '../x', 'review-1 --> <!--obs:review-2']) {
  let threw = false;
  try { buildRow({ ...base, id: bad }); } catch { threw = true; }
  check(`row: bad id rejected (${JSON.stringify(bad)})`, threw);
}

// ── Inline comments that came with a review ─────────────────────────────────
eq('inline: none gives nothing', inlineNote([]), '');
eq('inline: missing gives nothing', inlineNote(), '');
{
  const urls = (n) => Array.from({ length: n }, (_, i) => ({ url: `https://github.com/o/r/pull/1#discussion_r${i}` }));
  const three = inlineNote(urls(3));
  check('inline: three are counted and linked', three.includes('3 inline:') && three.includes('[3](') && !three.includes('\u2026+'), three);
  const eight = inlineNote(urls(8));
  check('inline: eight show five and a remainder', eight.includes('8 inline:') && eight.includes('[5](') && !eight.includes('[6](') && eight.includes('\u2026+3'), eight);
}

// ── The living comment ──────────────────────────────────────────────────────
const rowA = buildRow(base);
const rowB = buildRow({ ...base, id: 'comment-77', kind: 'comment', posted: '2026-10-17T22:10:00Z', stamp: null, excerpt: 'second' });
{
  const first = mergeLog('', rowA);
  check('log: first row makes a body with the marker first', first.body.startsWith(`${MARKER}\n`), first.body.slice(0, 60));
  check('log: has the start and end markers', first.body.includes(LOG_START) && first.body.includes(LOG_END));
  eq('log: one row', parseRows(first.body).map((row) => row.id), ['review-5561541']);

  const second = mergeLog(first.body, rowB);
  eq('log: a second row is appended in order', parseRows(second.body).map((row) => row.id), ['review-5561541', 'comment-77']);

  const again = mergeLog(second.body, rowB);
  check('log: applying the same row twice changes nothing', again.body === second.body);

  const edited = mergeLog(second.body, buildRow({ ...base, excerpt: 'rename it, and the other one', edited: true }));
  eq('log: an edit keeps the order', parseRows(edited.body).map((row) => row.id), ['review-5561541', 'comment-77']);
  check('log: an edit replaces the text', edited.body.includes('and the other one') && !edited.body.includes('| rename it <!--'));
  eq('log: an edit does not add a row', parseRows(edited.body).length, 2);
}
{
  const messy = ['hand-written intro', '', rowA.line, 'a stray line', '| not a row |', rowB.line, ''].join('\n');
  eq('log: rows survive a body with no markers and stray lines', parseRows(messy).map((row) => row.id), ['review-5561541', 'comment-77']);
  const rebuilt = mergeLog(messy, buildRow({ ...base, id: 'comment-99', kind: 'comment', excerpt: 'third' }));
  eq('log: a messy body is rebuilt with all rows', parseRows(rebuilt.body).map((row) => row.id), ['review-5561541', 'comment-77', 'comment-99']);
  check('log: the rebuilt body has the markers again', rebuilt.body.startsWith(MARKER) && rebuilt.body.includes(LOG_END));
}
eq('log: null old body is an empty log', parseRows(null), []);
check('log: text cannot forge a second row', (() => {
  const evil = buildRow({ ...base, id: 'comment-5', kind: 'comment', excerpt: makeExcerpt('x |\n| 1 | 2 | 3 | 4 | 5 | y <!--obs:review-1--> |') });
  return parseRows(mergeLog('', evil).body).length === 1;
})());
check('log: the time-zone note is there', mergeLog('', rowA).body.includes('Nothing here converts one to the other'));

// ── Reading the three webhook events ────────────────────────────────────────
// Shaped like GitHub's payloads: the same facts under different names.
const user = { login: 'Eaprime1', type: 'User' };
const reviewEv = {
  action: 'submitted', pull_request: { number: 462 },
  review: { id: 5561541, body: 'shepherd observation 202610171254', user, author_association: 'OWNER',
    submitted_at: '2026-10-17T21:54:00Z', commit_id: 'abc1234def5678', html_url: 'https://github.com/o/r/pull/462#pullrequestreview-5561541' },
};
const inlineEv = {
  action: 'created', pull_request: { number: 462 },
  comment: { id: 901, body: 'shepherd observation\nthis line', user, author_association: 'OWNER',
    created_at: '2026-10-17T21:55:00Z', commit_id: 'abc1234def5678', html_url: 'https://github.com/o/r/pull/462#discussion_r901' },
};
const prCommentEv = {
  action: 'created', issue: { number: 462, pull_request: { url: 'x' } },
  comment: { id: 77, body: 'shepherd observation 202610171600', user, author_association: 'OWNER',
    created_at: '2026-10-17T23:00:00Z', html_url: 'https://github.com/o/r/pull/462#issuecomment-77' },
};
{
  const read = readEvent('pull_request_review', reviewEv);
  check('event: review reads its id, kind and number', read.id === 'review-5561541' && read.kind === 'review' && read.prNumber === 462, JSON.stringify(read));
  check('event: review uses submitted_at and commit_id', read.posted === '2026-10-17T21:54:00Z' && read.head === 'abc1234def5678', JSON.stringify(read));
  check('event: review remembers its id for the inline lookup', read.reviewId === 5561541);
  check('event: review carries who, what and association', read.by === 'Eaprime1' && read.authorType === 'User' && read.association === 'OWNER' && read.body.startsWith('shepherd'));
  eq('event: submitted is not an edit', read.edited, false);
}
{
  const read = readEvent('pull_request_review_comment', inlineEv);
  check('event: review comment reads its id and kind', read.id === 'rcomment-901' && read.kind === 'inline' && read.prNumber === 462, JSON.stringify(read));
  check('event: review comment uses created_at and commit_id', read.posted === '2026-10-17T21:55:00Z' && read.head === 'abc1234def5678');
  eq('event: review comment has no review id to look up', read.reviewId, null);
}
{
  const read = readEvent('issue_comment', prCommentEv);
  check('event: PR comment reads its id, kind and number', read.id === 'comment-77' && read.kind === 'comment' && read.prNumber === 462, JSON.stringify(read));
  eq('event: PR comment has no head yet', read.head, null);
  check('event: an edit is flagged', readEvent('issue_comment', { ...prCommentEv, action: 'edited' }).edited === true);
}
eq('event: a comment on a plain issue is not read',
  readEvent('issue_comment', { action: 'created', issue: { number: 5 }, comment: prCommentEv.comment }), null);
eq('event: an unknown event is not read', readEvent('push', reviewEv), null);
eq('event: a name from Object.prototype is not read', readEvent('constructor', reviewEv), null);
eq('event: a PR comment with no comment object is not read',
  readEvent('issue_comment', { issue: { number: 1, pull_request: {} } }), null);
eq('event: a missing payload is not read', readEvent('issue_comment'), null);
eq('event: a review with no body object is not read', readEvent('pull_request_review', { pull_request: { number: 1 } }), null);
eq('event: a review with no PR number is not read', readEvent('pull_request_review', { review: reviewEv.review }), null);
{
  // End to end, without the network: event -> parse -> row -> log.
  const ev = readEvent('pull_request_review', reviewEv);
  const parsed = parseObservation(ev.body, { association: ev.association, authorType: ev.authorType });
  const row = buildRow({ ...ev, stamp: parsed.stamp, excerpt: parsed.excerpt, inline: [{ url: 'https://github.com/o/r/pull/462#discussion_r1' }] });
  const { body } = mergeLog('', row);
  check('end to end: the review lands as a row with both clocks',
    body.includes('| 202610172154 | 202610171254 |') && body.includes('1 inline:') && body.includes('`abc1234`'), body);
}

say(`${count - failed} of ${count} checks passed`);
process.exit(failed ? 1 : 0);
