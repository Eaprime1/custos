let failed = 0;
for (const [name, body, type, assoc, want] of rows) {
  const got = probatioRequests(body, type, assoc).map((c) => c.navigo);
  if (JSON.stringify(got) !== JSON.stringify(want)) {
    failed += 1;
    process.stdout.write(`FAIL ${name}: ${JSON.stringify(got)} != ${JSON.stringify(want)}\n`);
  }
}
async function requestDoesNotSetReadiness() {
  let writes = 0;
  const github = { rest: { issues: { addLabels: async () => { writes++; }, createComment: async () => { writes++; } } } };
  const core = { info: () => {} };
  await onComment({
    github,
    context: { repo: { owner: 'eaprime1', repo: 'custos' }, payload: {
      issue: { number: 1 },
      comment: { body: '^omnes probatio', user: { type: 'User' }, author_association: 'OWNER' },
    } },
    core,
  });
  if (writes !== 0) {
    failed += 1;
    process.stdout.write('FAIL request cue must not write readiness labels or comments\n');
  }
}
requestDoesNotSetReadiness().then(() => {
  process.stdout.write(String(rows.length - failed) + ' of ' + rows.length + ' passed\n');
  process.exit(failed ? 1 : 0);
});
