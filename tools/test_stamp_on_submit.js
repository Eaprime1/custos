'use strict';
// Offline test table for .github/scripts/stamp-on-submit.js. No network, no GitHub.
// Run: node tools/test_stamp_on_submit.js

const { decide, primaClock } = require('../.github/scripts/stamp-on-submit.js');

const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const OWNER = { login: 'Eaprime1', type: 'User', association: 'OWNER', owner: 'Eaprime1' };
const WHEN = '2026-10-31T03:19:23Z';
const LINE = 'prima-clock: 202610310319 UTC (stamped on submit)';

// Each row: name, input, and what must come back: 'skip:<reason>' or the stamped body.
const rows = [
  ['plain comment', { ...OWNER, body: 'option 1 would work well', when: WHEN }, `option 1 would work well\n\n${LINE}`],
  ['trailing newlines are trimmed', { ...OWNER, body: 'hello\n\n', when: WHEN }, `hello\n\n${LINE}`],
  ['crlf is kept', { ...OWNER, body: 'a\r\nb', when: WHEN }, `a\r\nb\r\n\r\n${LINE}`],
  ['typed stamp is left alone', { ...OWNER, body: 'prima observation 202610301841\nnote', when: WHEN },
    `prima observation 202610301841\nnote\n\n${LINE}`],
  ['quoted footer does not block', { ...OWNER, body: `> hello${FOOTER.replace(/\n/g, '\n> ')}\n\nyes please`, when: WHEN },
    null],
  ['seconds do not matter', { ...OWNER, body: 'x', when: '2026-10-31T03:19:59Z' }, `x\n\n${LINE}`],
  ['midnight rolls the date in UTC', { ...OWNER, body: 'x', when: '2026-12-31T23:59:59Z' },
    'x\n\nprima-clock: 202612312359 UTC (stamped on submit)'],
  ['offset times become UTC', { ...OWNER, body: 'x', when: '2026-10-30T20:19:23-07:00' }, `x\n\n${LINE}`],

  ['bot is skipped', { ...OWNER, type: 'Bot', body: 'x', when: WHEN }, 'skip:bot'],
  ['member is skipped', { ...OWNER, association: 'MEMBER', body: 'x', when: WHEN }, 'skip:not owner'],
  ['someone else claiming OWNER is skipped', { ...OWNER, login: 'someone', body: 'x', when: WHEN }, 'skip:not owner'],
  ['owner login in any case', { ...OWNER, login: 'eaprime1', body: 'x', when: WHEN }, `x\n\n${LINE}`],
  ['empty body', { ...OWNER, body: '', when: WHEN }, 'skip:empty'],
  ['whitespace body', { ...OWNER, body: ' \n ', when: WHEN }, 'skip:empty'],
  ['already stamped', { ...OWNER, body: `x\n\n${LINE}`, when: WHEN }, 'skip:already stamped'],
  ['footer (by)', { ...OWNER, body: `go${FOOTER}`, when: WHEN }, 'skip:footer'],
  ['footer (with)', { ...OWNER, body: 'go\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)', when: WHEN }, 'skip:footer'],
  ['open code fence', { ...OWNER, body: 'see\n```\ncode', when: WHEN }, 'skip:open fence'],
  ['closed code fence is fine', { ...OWNER, body: 'see\n```\ncode\n```', when: WHEN }, `see\n\`\`\`\ncode\n\`\`\`\n\n${LINE}`],
  ['bad time', { ...OWNER, body: 'x', when: 'not a time' }, 'skip:no time'],
];

let failed = 0;
const say = (text) => process.stdout.write(`${text}\n`);
const fail = (name, msg) => { failed += 1; say(`FAIL ${name}: ${msg}`); };

for (const [name, input, want] of rows) {
  const got = decide(input);
  if (name === 'quoted footer does not block') {
    // The footer is only inside the quote, so the owner's own words are stamped.
    if (got.action !== 'stamp' || !got.body.endsWith(LINE)) fail(name, JSON.stringify(got));
  } else if (want.startsWith('skip:')) {
    if (got.action !== 'skip' || got.reason !== want.slice(5)) fail(name, `${JSON.stringify(got)} != ${want}`);
  } else if (got.action !== 'stamp' || got.body !== want) {
    fail(name, `${JSON.stringify(got)} != ${JSON.stringify(want)}`);
  }
}

// Running it on its own output must do nothing.
const once = decide({ ...OWNER, body: 'again', when: WHEN });
const twice = decide({ ...OWNER, body: once.body, when: WHEN });
if (twice.action !== 'skip' || twice.reason !== 'already stamped') fail('idempotent', JSON.stringify(twice));

if (primaClock('2026-10-31T03:19:23Z') !== '202610310319') fail('primaClock', primaClock('2026-10-31T03:19:23Z'));

const total = rows.length + 2;
say(`${total - failed} of ${total} passed`);
process.exit(failed ? 1 : 0);
