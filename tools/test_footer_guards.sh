#!/usr/bin/env bash
# Offline test of the Claude Code footer guards in the seal path.
# It pulls the real guard text out of the workflow files, so it fails if a
# workflow drifts from the wording the guards are meant to catch.
# Needs bash, python3 with PyYAML, and node. Writes nothing to the repo.
set -uo pipefail
cd "$(dirname "$0")/.."

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
pass=0; fail=0
check() { # name expected got
  if [ "$2" = "$3" ]; then pass=$((pass+1)); else fail=$((fail+1)); echo "FAIL: $1 (expected $2, got $3)"; fi
}

BY=$'_Generated by [Claude Code](https://claude.ai/code)_'
WITH=$'\xf0\x9f\xa4\x96 Generated with [Claude Code](https://claude.com/claude-code)'
ODD='GENERATED With [claude code]'
PLAIN='generated with hand tools'

# 1. finalize-pr.yml: run the real gate step.
python3 - "$tmp/gate.sh" <<'PY'
import sys, yaml
d = yaml.safe_load(open('.github/workflows/finalize-pr.yml'))
step = [s for j in d['jobs'].values() for s in j['steps'] if s.get('id') == 'gate'][0]
open(sys.argv[1], 'w').write(step['run'])
PY
gate() {
  COMMENT_BODY="$1" GITHUB_OUTPUT="$tmp/out" bash "$tmp/gate.sh" >/dev/null 2>&1
  if grep -q 'triggered=true' "$tmp/out" 2>/dev/null; then echo seal; else echo skip; fi
  rm -f "$tmp/out"
}
check "finalize: cue alone seals"             seal "$(gate '@claude finalize')"
check "finalize: footer 'by' skips"           skip "$(gate "@claude finalize $BY")"
check "finalize: footer 'with' skips"         skip "$(gate "@claude finalize $WITH")"
check "finalize: footer odd case skips"       skip "$(gate "@claude finalize $ODD")"
check "finalize: plain words do not skip"     seal "$(gate "@claude finalize, $PLAIN")"
check "finalize: quoted cue skips"            skip "$(gate '> @claude finalize')"
check "finalize: ultima probatio seals"       seal "$(gate '@claude ultima probatio')"
check "finalize: ultima probatio + 'with'"    skip "$(gate "@claude ultima probatio $WITH")"

# 2. latin-cue-record.yml: run the real footer expression.
expr=$(python3 - <<'PY'
import re
src = open('.github/workflows/latin-cue-record.yml').read()
print(re.search(r"if \((\[.*?\]\.some\(.*?\))\) \{", src).group(1))
PY
)
rec() { node -e "const t=(raw)=>$expr; console.log(t(process.argv[1]) ? 'skip' : 'go')" "$1"; }
check "record: footer 'by' skips"             skip "$(rec "$BY")"
check "record: footer 'with' skips"           skip "$(rec "$WITH")"
check "record: footer odd case skips"         skip "$(rec "$ODD")"
check "record: plain words do not skip"       go   "$(rec "$PLAIN")"

# 3. placet.yml: each guard literal, matched the way contains() does (case-insensitive).
lits=$(grep -o "contains(github.event.comment.body, '[^']*')" .github/workflows/placet.yml | sed "s/.*, '//; s/')//")
plc() {
  local low; low=$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')
  while IFS= read -r l; do
    [ -n "$l" ] && case "$low" in *"$(printf '%s' "$l" | tr '[:upper:]' '[:lower:]')"*) echo skip; return;; esac
  done <<< "$lits"
  echo go
}
check "placet: footer 'by' skips"             skip "$(plc "$BY")"
check "placet: footer 'with' skips"           skip "$(plc "$WITH")"
check "placet: footer odd case skips"         skip "$(plc "$ODD")"
check "placet: plain words do not skip"       go   "$(plc "$PLAIN")"

echo "$pass of $((pass+fail)) passed"
[ "$fail" -eq 0 ]
